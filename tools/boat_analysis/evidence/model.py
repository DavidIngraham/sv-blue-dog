"""Project immutable run evidence into named SysML instances, without re-solving."""
import argparse
import json

from .records import BASELINE, CURRENT, run_record
from tools.boat_analysis.model.runtime import ROOT


def model_source(directory=BASELINE, package="BlueDogRecordedSizing"):
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    search = run_record(directory, "coupled-sizing-search.json")
    replay = run_record(directory, "coupled-sizing-replay.json")
    literal = lambda value: ("true" if value else "false") if isinstance(value, bool) else format(value, ".17g")
    vector = lambda values: "(" + ",".join(literal(value) for value in values) + ")"
    lines = ["// Generated by tools.boat_analysis.evidence.model; edit source evidence only through a new recorded run.",
             f"package {package} {{", "    private import ScalarValues::*;",
             f'    doc /* Exploratory run at source revision {manifest["sourceRevision"]}.',
             f'     * Evidence: {directory.relative_to(ROOT).as_posix()}/manifest.json.',
             ('     * Frozen conservative-policy rerun; publishing this projection does not execute a new solve. */'
              if directory == CURRENT else '     * This projection preserves the recorded run, not a rerun of the current model. */'),
             '    part candidate : MarineDesign::Design {']
    for name, value in search["design"].items():
        lines.append(f"        attribute :>> {name} = {literal(value)};")
    lines += ["    }"]
    if directory == CURRENT:
        bounds = [f'{name} ({side}, {bound:g})'
                  for name, limits in search['designBounds'].items()
                  for side, bound in zip(('lower', 'upper'), limits)
                  if abs(search['design'][name]-bound) <= 1e-6 * max(1, limits[1]-limits[0])]
        lines += ['    part searchAssessment {',
                  f'        attribute solverStatus : String = {json.dumps(search["optimizerMessage"])};',
                  f'        attribute activeBounds : String = {json.dumps("; ".join(bounds) or "none")};',
                  f'        attribute coarseFeasible : Boolean = {literal(search["coarseFeasible"])};',
                  f'        attribute massKg : Real = {literal(search["mass"]["totalMass"])};',
                  f'        attribute maximumResidual : Real = {literal(search["maxEquilibriumResidual"])};',
                  f'        attribute minimumMargin : Real = {literal(search["minimumMargin"])};',
                  f'        attribute progressReserveMps : Real = {literal(search["progressSearchReserve_m_s"])};',
                  '        attribute qualified : Boolean = false;', '    }']
        for index, (label, margin) in enumerate(search['worstConstraints']):
            if label.endswith(('upstream progress', 'downstream progress')):
                label += ' (with numerical search reserve)'
            lines += [f'    part searchConstraint{index} {{', f'        attribute label : String = "{label}";',
                      f'        attribute margin : Real = {literal(margin)};', '    }']
        convergence = run_record(directory, 'wing-convergence.json')
        for index, check in enumerate(convergence['comparisons']):
            label = f"{'reverse' if check['reverseChord'] else 'forward'}, beta {check['beta_deg']}, {check['comparison']}"
            lines += [f'    part convergence{index} {{', f'        attribute label : String = "{label}";',
                      f'        attribute passesScreen : Boolean = {literal(check["passesScreen"])};']
            lines += [f'        attribute {key} : Real = {literal(value)};' for key, value in check['maxAbsoluteDifference'].items()]
            lines += ['    }']
        for index, (reverse, beta) in enumerate(((False, 0), (True, 0), (False, 20))):
            cases = [c for c in convergence['cases'] if c['reverseChord'] == reverse and c['beta_deg'] == beta]
            lines += [f'    part coarseGrid{index} {{',
                      f'        attribute label : String = "{"reverse" if reverse else "forward"}, beta {beta}: mesh 24/wake 5 to mesh 72/wake 30";']
            for key in ('CLtot', 'CDi', 'CMytot'):
                difference = max(abs(a-b) for a,b in zip(cases[0]['values'][key], cases[-1]['values'][key]))
                lines += [f'        attribute {key} : Real = {literal(difference)};']
            lines += ['    }']
        lines += ['    dependency assumptions from candidate to BlueDogAerodynamicPolicy::sizing;',
                  '    dependency convergenceBasis from convergence0 to BlueDogAerodynamicPolicy::convergenceInputs;']
        recovery = run_record(directory, 'coupled-recovery.json')
        combinations = [(density, state) for density in (1000, 1025)
                        for state in ('sealed', 'free_flooding_homogenized', 'full_water_retention')]
        for index, (density, state) in enumerate(combinations):
            cases = [c for c in recovery['cases'] if c['density_kg_m3'] == density and c['wing_state'] == state]
            resolved = [c['minimumInteriorRestoring_Nm'] for c in cases if c['minimumInteriorRestoring_Nm'] is not None]
            values = {'minimumRestoringNm': min(resolved),
                      'missingPitchRoots': sum(c['failedEquilibria'] for c in cases),
                      'unstablePitchSamples': sum(not p.get('pitch_stable', False) for c in cases for p in c['points'] if 'failure' not in p),
                      'retainedWaterKg': max(c['retained_water_kg'] for c in cases)}
            lines += [f'    part ingress{index} {{', f'        attribute label : String = "{state}, water {density} kg/m3";']
            lines += [f'        attribute {key} : {"Integer" if isinstance(value, int) else "Real"} = {literal(value)};' for key, value in values.items()]
            lines += ['    }', f'    dependency ingressBasis{index} from ingress{index} to BlueDogRequirements::selfRighting;']
    for record in replay["scenarios"]:
        name = record["scenario"]
        missing = sum(curve["failedEquilibria"] for curve in record["recovery"])
        unstable = sum(not p.get("pitch_stable", False) for c in record["recovery"] for p in c["points"] if "failure" not in p)
        scalar = {
            "numericallyBalanced": record["numericallyBalanced"],
            "missingPitchRoots": missing,
            "pitchUnstableSamples": unstable,
            "diagnosticControlCases": sum(not c["energyConstraintsEnforced"] for c in record["cases"]),
            "easterlyHours": record["route"][5], "westerlyHours": record["westerlyRoute"][5],
            "massKg": record["cases"][0]["outputs"]["mass_kg"], "evidenceAccepted": False,
        }
        sequence = {
            "operatingMargins": [record["minimumOperatingMargin"]],
            "structuralMargins": list(record["structure"].values()),
            "routeMargins": record["route"][:3] + record["westerlyRoute"][:3],
            "restoringMomentsNm": [c["minimumInteriorRestoring_Nm"] for c in record["recovery"]],
        }
        label = "conservative primary" if directory == CURRENT and name == "nominal" else name
        lines += [f"    part {name} : BlueDogSizingEvidence::Scenario {{", f'        attribute :>> label = "{label}";']
        if directory == CURRENT:
            margins = {**record['structure'], 'operating/energy': record['minimumOperatingMargin']}
            for direction, route in (('easterly', record['route']), ('westerly', record['westerlyRoute'])):
                margins.update({f'{direction} {key}': value for key, value in zip(('downstream progress', 'upstream progress', 'duration'), route[:3])})
            detail = '; '.join(f'{key}: {value:.4g}' for key, value in sorted(margins.items(), key=lambda item: item[1])[:3])
            if not record['numericallyBalanced']:
                detail = 'Force/moment balance not converged; ' + detail
            lines += [f'        attribute limitingScreens : String = {json.dumps(detail)};']
            for direction, route in (('easterly', record['route']), ('westerly', record['westerlyRoute'])):
                lines += [f'        attribute {direction}DownstreamMps : Real = {literal(route[3])};',
                          f'        attribute {direction}UpstreamMps : Real = {literal(route[4])};',
                          f'        attribute {direction}TimeLabel : String = if {direction}DownstreamMps <= 0 or {direction}UpstreamMps <= 0 ? "No completion (duration penalty)" else "{route[5]:.4g}";']
        lines += [f"        attribute :>> {key} = {literal(value)};" for key, value in scalar.items()]
        lines += [f"        attribute :>> {key} = {vector(value)};" for key, value in sequence.items()]
        lines += ["    }", f"    analysis {name}Review : BlueDogSizingEvidence::Review {{ subject :>> scenario = {name}; }}"]
    lines += ["    dependency candidateBasis from candidate to BlueDogDesignDecisions::sizingBaseline;", "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--current", action="store_true", help="Project the current conservative run, preserving historical instances")
    args = parser.parse_args()
    path = ROOT / ("models/evidence/conservative-2026-10-11.sysml" if args.current else "models/evidence/coupled-2026-10-10.sysml")
    source = model_source(CURRENT, "BlueDogCurrentSizing") if args.current else model_source()
    if args.check:
        if path.read_text(encoding="utf-8") != source:
            raise SystemExit("Stale recorded-evidence model")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
