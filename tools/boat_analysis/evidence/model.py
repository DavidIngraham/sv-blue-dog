"""Project immutable run evidence into named SysML instances, without re-solving."""
import argparse
import json

from .records import BASELINE, baseline_record
from tools.boat_analysis.model.runtime import ROOT


def model_source():
    manifest = json.loads((BASELINE / "manifest.json").read_text(encoding="utf-8"))
    search = baseline_record("coupled-sizing-search.json")
    replay = baseline_record("coupled-sizing-replay.json")
    literal = lambda value: ("true" if value else "false") if isinstance(value, bool) else format(value, ".17g")
    vector = lambda values: "(" + ",".join(literal(value) for value in values) + ")"
    lines = ["// Generated by tools.boat_analysis.evidence.model; edit source evidence only through a new recorded run.",
             "package BlueDogRecordedSizing {", "    private import ScalarValues::*;",
             f'    doc /* Exploratory run at source revision {manifest["sourceRevision"]}.',
             '     * Evidence: evidence/runs/2026-10-10-coupled/manifest.json.',
             '     * This projection preserves the recorded run, not a rerun of the current model. */',
             '    part candidate : MarineDesign::Design {']
    for name, value in search["design"].items():
        lines.append(f"        attribute :>> {name} = {literal(value)};")
    lines += ["    }"]
    for record in replay["scenarios"]:
        name = record["scenario"]
        missing = sum(curve["failedEquilibria"] for curve in record["recovery"])
        unstable = sum(not p.get("pitch_stable", False) for c in record["recovery"] for p in c["points"] if "failure" not in p)
        scalar = {
            "numericallyBalanced": record["numericallyBalanced"],
            "missingPitchRoots": missing,
            "pitchUnstableSamples": unstable,
            "diagnosticControlCases": sum(not c["energyConstraintsEnforced"] for c in record["cases"]),
            "easterlyHours": record["route"][5], "westerlyHours": record["westerlyRoute"][5],
            "massKg": record["cases"][0]["outputs"]["mass_kg"], "evidenceAccepted": False,
        }
        sequence = {
            "operatingMargins": [record["minimumOperatingMargin"]],
            "structuralMargins": list(record["structure"].values()),
            "routeMargins": record["route"][:3] + record["westerlyRoute"][:3],
            "restoringMomentsNm": [c["minimumInteriorRestoring_Nm"] for c in record["recovery"]],
        }
        lines += [f"    part {name} : BlueDogSizingEvidence::Scenario {{", f'        attribute :>> label = "{name}";']
        lines += [f"        attribute :>> {key} = {literal(value)};" for key, value in scalar.items()]
        lines += [f"        attribute :>> {key} = {vector(value)};" for key, value in sequence.items()]
        lines += ["    }", f"    analysis {name}Review : BlueDogSizingEvidence::Review {{ subject :>> scenario = {name}; }}"]
    lines += ["    dependency candidateBasis from candidate to BlueDogDesignDecisions::sizingBaseline;", "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "models/evidence/coupled-2026-10-10.sysml"
    source = model_source()
    if args.check:
        if path.read_text(encoding="utf-8") != source:
            raise SystemExit("Stale recorded-evidence model")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
