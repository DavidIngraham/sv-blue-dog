"""Publish an immutable local sizing study as native model evidence and a plot."""
import argparse
import json
from tools.boat_analysis.evidence.records import ROOT, run_record


def render(run):
    directory = ROOT / 'evidence/runs' / run
    record = run_record(directory, 'srr-frontier.json')
    replay = run_record(directory, 'srr-candidate-replay.json')
    rows = record['candidates']
    lines = ['// Generated by tools.publishing.frontier; edit the source analysis, not these values.',
             'package BlueDogSRRFrontier {', '    private import ScalarValues::*;',
             '    doc /* Local coarse monohull search, not physical qualification or a calibrated mission probability.',
             '     * Unresolved searches do not prove infeasibility. The replay applies to the retained seed, not every alternative. */',
             f'    attribute evidenceManifest : String = "evidence/runs/{run}/manifest.json";',
             '    attribute pointNames : String [*] ordered nonunique = (' + ', '.join(json.dumps(f'BlueDogSRRFrontier::point{i}') for i in range(len(rows))) + ');']
    def field(name, value):
        kind = 'Boolean' if isinstance(value, bool) else 'String' if isinstance(value, str) else 'Real'
        return f'        attribute {name} : {kind} = {json.dumps(value, allow_nan=False)};'
    for i, row in enumerate(rows):
        lines.append(f'    part point{i} {{')
        for key in ['capM','objective','feasible','solverConverged','overallLengthM','massKg','conditionalPassageHours','maxEquilibriumResidual','minimumMargin']:
            if key in row:
                lines.append(field('optimizationObjective' if key=='objective' else key,row[key]))
        lines.append('    }')
    lines.append('    part retainedSeedReplay {')
    values = dict(massKg=replay['retainedSeedMassKg'], westerlyHours=replay['westerlyRoute'][5],
                  numericallyBalanced=replay['numericallyBalanced'],
                  voyageEnergyMargin=replay['structure']['voyageEnergyMargin'],
                  sampledRightingPass=all(r['failedEquilibria']==0 and r['minimumInteriorRestoring_Nm']>0 for r in replay['recovery']),
                  profileScreensPass=replay['profileSampledStaticScreensPass'],qualified=False)
    lines.extend(field(k,v) for k,v in values.items())
    lines += ['    }','}']
    (ROOT/'models/evidence/srr-frontier.sysml').write_text('\n'.join(lines)+'\n',encoding='utf-8')

    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'svg.hashsalt':'blue-dog-srr-frontier','svg.fonttype':'none','font.size':11})
    fig,ax=plt.subplots(figsize=(8,5),layout='constrained')
    for row in rows:
        if row['feasible']:
            marker='o' if row['objective']=='massKg' else '^'
            ax.scatter(row['massKg'],row['conditionalPassageHours'],marker=marker,s=75,
                       label=f"{row['capM']:g} m cap / {'mass' if marker=='o' else 'passage'} objective")
    ax.set(xlabel='Mass (kg)',ylabel='Conditional steady westerly passage (h)',title='Local sizing alternatives that pass coarse screens')
    if any(r['feasible'] for r in rows): ax.legend(frameon=False,fontsize=9)
    else: ax.text(.5,.5,'No feasible candidate found in this bounded search',ha='center',transform=ax.transAxes)
    unresolved=sorted({r['capM'] for r in rows if not any(q['feasible'] for q in rows if q['capM']==r['capM'])})
    ax.ticklabel_format(useOffset=False,style='plain')
    feasible=[r for r in rows if r['feasible']]
    if feasible:
        masses=[r['massKg'] for r in feasible];hours=[r['conditionalPassageHours'] for r in feasible]
        ax.set_xlim(min(masses)-.5,max(masses)+.5)
        ax.set_ylim(min(hours)-1,max(hours)+1)
    ax.grid(alpha=.2)
    fig.supxlabel('Unresolved caps: '+(', '.join(f'{v:g} m' for v in unresolved) or 'none')+' · No physical qualification',fontsize=10)
    output=ROOT/'docs/figures/srr-frontier.svg'
    fig.savefig(output,metadata={'Date':None,'Description':'Bounded local search; no interpolation, global optimum or real-world reliability claim.'})
    output.write_text('\n'.join(line.rstrip() for line in output.read_text(encoding='utf-8').splitlines())+'\n',encoding='utf-8')
    plt.close(fig)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run',required=True)
    render(parser.parse_args().run)
