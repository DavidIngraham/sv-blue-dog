"""Render the current SRR candidate record into traceable native model evidence."""
import argparse
import json
from tools.boat_analysis.evidence.records import ROOT, run_record


def render(run):
    record=run_record(ROOT/'evidence/runs'/run, 'srr-readiness.json')
    replay=record['refinedReplay']
    concept=replay['concept']
    fields=dict(batteryWh=record['design']['battery_Wh'],hullBeamM=record['design']['beam_m'],
                massKg=record['coarseReplay']['massKg'],
                westerlyPassageHours=replay['westerlyRoute'][5],
                departureWh=concept['departureWh'],requiredWh=concept['requiredWh'],
                energyHeadroomWh=concept['departureWh']-concept['requiredWh'],
                balanced=replay['numericallyBalanced'],
                staticScreensPass=replay['profileSampledStaticScreensPass'],
                physicallyQualified=False)
    lines=['// Generated by tools.publishing.srr from immutable run evidence.',
           'package BlueDogSRRCurrent {', '    private import ScalarValues::*;',
           f'    attribute evidenceManifest : String = "evidence/runs/{run}/manifest.json";',
           '    part candidate {']
    for name,value in fields.items():
        kind='Boolean' if isinstance(value,bool) else 'Real'
        lines.append(f'        attribute {name} : {kind} = {json.dumps(value,allow_nan=False)};')
    lines+=['        doc /* Retained concept with revised battery capacity and hull beam; nominal refined static replay.',
            '         * Not a new optimum, hardware selection, dynamic recovery proof or mission qualification. */',
            '    }',
            '    dependency energyBasis from candidate to BlueDogConceptCredibility::passagePolicy;',
            '    dependency recoveryBasis from candidate to BlueDogRequirements::lowEnergyRecovery;',
            '}']
    (ROOT/'models/evidence/srr-current.sysml').write_bytes(('\n'.join(lines)+'\n').encode())


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run',required=True)
    render(parser.parse_args().run)
